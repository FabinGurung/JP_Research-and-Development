#!/usr/bin/env python3
"""Hard gate for Enterprise client-visible LaTeX and PDFs.

Policy is about VISIBLE business documents only. Internal filenames,
structured evidence, status records and historical sources remain traceable.
A successful lint check does NOT imply legal or commercial approval.
"""
import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
POLICY=ROOT/"controls/document-engineering/client-facing-language.policy.json"

def violations(text):
    if not isinstance(text,str):
        raise ValueError("Visible content must be text")
    policy=json.loads(POLICY.read_text(encoding="utf-8"))
    result=[]
    for phrase in policy["forbidden_visible_phrases"]:
        pat=r"(?<![A-Za-z0-9])"+re.escape(phrase)+r"(?![A-Za-z0-9])"
        if re.search(pat,text,re.IGNORECASE):
            result.append(phrase)
    for row in policy.get("forbidden_visible_patterns",[]):
        if re.search(row["regex"],text,re.IGNORECASE):
            result.append(row["id"])
    return result

def visible_tex_text(source):
    """Conservative static LaTeX source inspection (final PDF is authoritative).

    Remove comments, unescape common text macros, and retain macro *arguments*
    which can print in the PDF. Intended for fully rendered project .tex,
    not original version-controlled .sty source and not private JSON metadata.
    """
    lines=[]
    for line in source.splitlines():
        line=re.split(r"(?<!\\)%",line,maxsplit=1)[0]
        lines.append(line)
    text="\n".join(lines)
    text=text.replace(r"\_", "_").replace(r"\%", "%")
    return text

def check_tex(path):
    body=visible_tex_text(Path(path).read_text(encoding="utf-8"))
    if not body.strip():
        raise ValueError("Generated TeX has no checkable content")
    errors=violations(body)
    if errors:
        raise ValueError("Client-visible LaTeX contains internal identifiers/status: "+", ".join(errors))
    return len(body)

def check_pdf(path):
    if not shutil.which("pdftotext"):
        raise RuntimeError("pdftotext unavailable; cannot approve PDF")
    body=subprocess.check_output(["pdftotext","-layout",str(path),"-"],text=True)
    if not body.strip():
        raise ValueError("PDF has no extractable text; require visual checking")
    errors=violations(body)
    if errors:
        raise ValueError("Client-facing PDF contains internal identifiers/status: "+", ".join(errors))
    return len(body)

def selftest():
    good=(
        "Construction works agreement for Radha Roka Residence.",
        "Issued by Rohini Engineering and Builders for uPVC windows and MS railings.",
        "Receipt no. 123; invoice INV-2026-041; payable in NPR."
    )
    bad=(
        "DRAFT - 07_Example_Client", "Generated by ChatGPT and database",
        "PRJ-000007","ORG-000001","client_contract","project_identifier",
        "NOT FOR SIGNATURE","Internal use only","fictional sample",
        "The A9 control tower approved this document")
    assert all(not violations(s) for s in good)
    assert all(violations(s) for s in bad)
    assert not violations("Paid invoice; main gate; mountain view; claim.")
    assert violations(visible_tex_text(r"\EnterpriseField{Project}{07\_Example\_Client}"))
    assert not violations(visible_tex_text(r"% DRAFT internal metadata"+"\n"+r"\EnterpriseField{Project}{Example Residence}"))
    print("PASS Enterprise v1.1 visible-source/PDF semantics and human-readable names")

if __name__=="__main__":
    ap=argparse.ArgumentParser()
    ap.add_argument("--pdf",type=Path)
    ap.add_argument("--tex",type=Path)
    ap.add_argument("--text-file",type=Path)
    ap.add_argument("--self-test",action="store_true")
    args=ap.parse_args()
    if args.self_test:selftest()
    elif args.pdf:
        print("PASS PDF visible language; characters:",check_pdf(args.pdf))
    elif args.tex:
        print("PASS TeX client-visible source; characters:",check_tex(args.tex))
    elif args.text_file:
        errors=violations(args.text_file.read_text(encoding="utf-8"))
        if errors:raise SystemExit("BLOCKED client wording: "+", ".join(errors))
        print("PASS visible text")
    else:
        ap.error("Use --pdf, --tex, --text-file or --self-test")
